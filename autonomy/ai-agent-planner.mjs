const WEB_APP_ACTIONS = [
  ['architecture', 'Define application architecture and acceptance criteria', 'plan-only', ['architecture-recorded']],
  ['scaffold', 'Prepare the application scaffold and runtime contract', 'builder-scaffold', ['scaffold-recorded']],
  ['validate', 'Validate the generated application structure', 'builder-validate', ['structure-validated']],
  ['security', 'Run the native security and policy gate', 'builder-security', ['security-gate-passed']],
  ['test', 'Run application tests and record evidence', 'builder-test', ['tests-passed']],
  ['package', 'Package the application as a portable workload', 'builder-package', ['artifact-recorded']],
];

export function inferPlanSteps(goal = '') {
  const text = String(goal).trim();
  if (!text) throw new Error('goal is required');

  const lower = text.toLowerCase();
  const webIntent = /\b(web|website|app|application|platform|portal|dashboard|site|service)\b/.test(lower);
  const selected = webIntent ? WEB_APP_ACTIONS : WEB_APP_ACTIONS.filter(([key]) => ['architecture', 'security', 'test', 'package'].includes(key));

  return selected.map(([key, title, action, evidence], index) => ({
    id: `auto-${key}-${index + 1}`,
    title: `${title}: ${text}`,
    action,
    status: 'queued',
    dependsOn: index ? [`auto-${selected[index - 1][0]}-${index}`] : [],
    evidence,
    goal: text,
  }));
}

export function isAutogeneratedPlan(plan) {
  return Array.isArray(plan?.steps) && plan.steps.length > 0 && plan.steps.every((step) => step.id.startsWith('auto-'));
}
