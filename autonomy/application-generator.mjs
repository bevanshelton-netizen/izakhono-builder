function loadTemplateCatalog() {
  const file = fileURLToPath(new URL('../templates/native-applications.v1.json', import.meta.url));
  const catalog = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (catalog.schema !== 'izakhono.application-template-catalog/v1' || !Array.isArray(catalog.templates)) {
    throw new Error('application-template-catalog-invalid');
  }
  return catalog;
}

export function availableApplicationTemplates() {
  return Object.freeze(loadTemplateCatalog().templates.map((template) => ({
    id: template.id,
    version: template.version,
    description: template.description,
    fileCount: template.files.length,
    externalAiRequired: template.externalAiRequired,
  })));
}

export function scaffoldApplication({ workspaceRoot, projectId, name, goal, templateId = 'static-web' }) {
  if (!workspaceRoot) throw new Error('application-workspace-required');
  const id = safeProjectId(projectId);
  const project = {
    id,
    name: String(name || id).trim().slice(0, 120),
    goal: String(goal || '').trim().slice(0, 4000),
  };
  if (!project.goal) throw new Error('application-goal-required');
  const catalog = loadTemplateCatalog();
  const template = catalog.templates.find((entry) => entry.id === templateId);
  if (!template) throw new Error('application-template-unsupported');
  const files = templateId === 'static-web' ? websiteTemplate(project)
    : templateId === 'node-api' ? apiTemplate(project) : null;
  if (!files) throw new Error('application-template-implementation-missing');
  const actualFiles = Object.keys(files).sort();
  const expectedFiles = [...template.files].sort();
  if (JSON.stringify(actualFiles) !== JSON.stringify(expectedFiles)) throw new Error('application-template-catalog-mismatch');
  if (actualFiles.length > MAX_FILES) throw new Error('application-template-file-limit');
  const root = path.resolve(workspaceRoot);
  fs.mkdirSync(root, { recursive: true });
  const manifestPath = path.join(root, 'izakhono.application.json');
  if (fs.existsSync(manifestPath)) {
    const existing = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    if (existing.projectId !== id || existing.templateId !== templateId || existing.templateVersion !== template.version) throw new Error('application-workspace-conflict');
    const missing = existing.files.filter((relative) => !fs.existsSync(ensureInside(root, safeRelativePath(relative))));
    if (missing.length) throw new Error('application-workspace-incomplete');
    return { ...existing, fileCount: existing.files.length + 1, workspaceRoot: root, reused: true };
  }
  const unexpected = fs.readdirSync(root).filter((entry) => entry !== 'architecture.json' && entry !== '.izakhono');
  if (unexpected.length) throw new Error('application-workspace-not-empty');
  for (const [relative, content] of Object.entries(files)) {
    const target = ensureInside(root, safeRelativePath(relative));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, { encoding: 'utf8', flag: 'wx' });
  }
  const manifest = {
    schema: 'izakhono.application-scaffold/v1',
    projectId: id,
    templateId,
    templateVersion: template.version,
    files: actualFiles,
    generation: 'deterministic-native',
    externalAiRequired: false,
  };
  fs.writeFileSync(manifestPath, json(manifest), { flag: 'wx' });
  return { ...manifest, fileCount: manifest.files.length + 1, workspaceRoot: root, reused: false };
}

function listFiles(root, current = root, result = []) {
  for (const entry of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    if (current === root && ['.git', '.izakhono', 'node_modules'].includes(entry.name)) continue;
    const absolute = path.join(current, entry.name);
    if (entry.isSymbolicLink()) throw new Error('snapshot-symlink-not-allowed');
    if (entry.isDirectory()) listFiles(root, absolute, result);
    else if (entry.isFile()) result.push(absolute);
    else throw new Error('snapshot-special-file-not-allowed');
  }
  return result;
}

export function createCanonicalSnapshot({ workspaceRoot, repositoryRoot }) {
  if (!workspaceRoot || !repositoryRoot) throw new Error('snapshot-roots-required');
  const root = fs.realpathSync(workspaceRoot);
  const repository = path.resolve(repositoryRoot);
  const entries = [];
  let totalBytes = 0;
  const files = listFiles(root);
  if (files.length === 0 || files.length > MAX_FILES) throw new Error('snapshot-file-count-invalid');
  for (const file of files) {
    const relative = path.relative(root, file).split(path.sep).join('/');
    const data = fs.readFileSync(file);
    if (data.length > MAX_FILE_BYTES) throw new Error('snapshot-file-size-limit');
    totalBytes += data.length;
    const hash = crypto.createHash('sha256').update(data).digest('hex');
    entries.push({ path: relative, sha256: hash, size: data.length });
  }
  entries.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
  const canonical = entries.map((entry) => entry.path + '\0' + entry.sha256 + '\n').join('');
  const snapshotHash = crypto.createHash('sha256').update(canonical, 'utf8').digest('hex');
  const objectRoot = path.join(repository, 'objects');
  const snapshotRoot = path.join(repository, 'snapshots');
  fs.mkdirSync(objectRoot, { recursive: true });
  fs.mkdirSync(snapshotRoot, { recursive: true });
  for (const file of files) {
    const data = fs.readFileSync(file);
    const hash = crypto.createHash('sha256').update(data).digest('hex');
    const objectPath = path.join(objectRoot, hash.slice(0, 2), hash.slice(2));
    fs.mkdirSync(path.dirname(objectPath), { recursive: true });
    if (!fs.existsSync(objectPath)) fs.writeFileSync(objectPath, data, { flag: 'wx' });
    else if (!fs.readFileSync(objectPath).equals(data)) throw new Error('snapshot-object-hash-collision');
  }
  const manifest = {
    schema: 'izakhono.repository-snapshot/v1',
    algorithm: 'sha256',
    snapshotHash,
    fileCount: entries.length,
    totalBytes,
    files: entries,
  };
  const manifestPath = path.join(snapshotRoot, snapshotHash + '.json');
  if (!fs.existsSync(manifestPath)) fs.writeFileSync(manifestPath, json(manifest), { flag: 'wx' });
  else if (fs.readFileSync(manifestPath, 'utf8') !== json(manifest)) throw new Error('snapshot-manifest-conflict');
  return { snapshotHash, fileCount: entries.length, totalBytes, manifestPath, objectRoot };
}
