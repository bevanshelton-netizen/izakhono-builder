import assert from 'node:assert/strict';
import { inferPlanSteps, isAutogeneratedPlan } from './ai-agent-planner.mjs';

const webPlan = inferPlanSteps('Build a customer web application for KORA');
assert.equal(webPlan.length, 7);
assert.equal(webPlan[0].action, 'plan-only');
assert.equal(webPlan[1].action, 'builder-scaffold');
assert.equal(webPlan[2].action, 'builder-generate');
assert.equal(webPlan.at(-1).action, 'builder-package');
assert.deepEqual(webPlan[1].dependsOn, [webPlan[0].id]);
assert.ok(isAutogeneratedPlan({ steps: webPlan }));

const genericPlan = inferPlanSteps('Improve operational security');
assert.equal(genericPlan.length, 4);
assert.ok(genericPlan.every((step) => step.evidence.length > 0));

console.log('[PASS] Native AI agent planner decomposes goals into dependency-aware executable steps.');
