create table if not exists public.business_engine_artifacts (
  id uuid primary key default gen_random_uuid(),
  workspace_id text not null,
  campaign_id text,
  job_id text,
  step_id text,
  artifact_type text not null,
  idempotency_key text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (workspace_id, idempotency_key)
);

create index if not exists business_engine_artifacts_workspace_idx
  on public.business_engine_artifacts (workspace_id, created_at desc);

create index if not exists business_engine_artifacts_job_idx
  on public.business_engine_artifacts (job_id, created_at desc);

alter table public.business_engine_artifacts enable row level security;

comment on table public.business_engine_artifacts is
  'Idempotent execution manifests and provider artifacts generated by IZAKHONO BUSINESS ENGINE.';
