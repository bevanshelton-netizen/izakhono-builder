#!/usr/bin/env bash
set -euo pipefail

read_env() {
  local key="$1" line value
  line="$(grep -m1 -E "^$key=" .env 2>/dev/null || true)"
  value="${line#*=}"
  value="${value%\"}"; value="${value#\"}"
  value="${value%\'}"; value="${value#\'}"
  printf '%s' "$value"
}

HOSTNAME="${MAIL_HOSTNAME:-$(read_env MAIL_HOSTNAME)}"
DOMAIN="${MAIL_DOMAIN:-$(read_env MAIL_DOMAIN)}"
WEBMAIL="${WEBMAIL_HOSTNAME:-$(read_env WEBMAIL_HOSTNAME)}"
DKIM_SELECTOR="${DKIM_SELECTOR:-$(read_env DKIM_SELECTOR)}"
HOSTNAME="${HOSTNAME:-mail.izakhonoafrica.co.za}"
DOMAIN="${DOMAIN:-izakhonoafrica.co.za}"
WEBMAIL="${WEBMAIL:-webmail.izakhonoafrica.co.za}"

fail=0
check() {
  local label="$1"; shift
  if "$@" >/dev/null 2>&1; then
    echo "PASS: $label"
  else
    echo "BLOCKED: $label"
    fail=1
  fi
}

for command in dig nc openssl curl timeout; do
  command -v "$command" >/dev/null || { echo "BLOCKED: $command is required"; exit 1; }
done

check "A record for ${HOSTNAME}" dig +short A "$HOSTNAME"
check "A record for ${WEBMAIL}" dig +short A "$WEBMAIL"
check "MX record for ${DOMAIN}" bash -c "dig +short MX '$DOMAIN' | grep -qi '$HOSTNAME'"
check "SPF record for ${DOMAIN}" bash -c "dig +short TXT '$DOMAIN' | grep -qi 'v=spf1'"
check "DMARC record for ${DOMAIN}" bash -c "dig +short TXT '_dmarc.$DOMAIN' | grep -qi 'v=DMARC1'"

if [[ -n "$DKIM_SELECTOR" ]]; then
  check "DKIM record for ${DKIM_SELECTOR}._domainkey.${DOMAIN}" bash -c "dig +short TXT '$DKIM_SELECTOR._domainkey.$DOMAIN' | grep -qi 'v=DKIM1'"
else
  echo "BLOCKED: set DKIM_SELECTOR to the exact selector generated by Stalwart."
  fail=1
fi

check "PTR resolves to ${HOSTNAME}" bash -c 'ip=$(dig +short A "$1" | head -n1); test -n "$ip" && dig +short -x "$ip" | grep -qi "$2."' _ "$HOSTNAME" "$HOSTNAME"

for port in 25 465 587 993; do
  check "TCP ${HOSTNAME}:${port}" nc -z -w 8 "$HOSTNAME" "$port"
done

check "SMTP STARTTLS on port 25" bash -c "echo | timeout 12 openssl s_client -starttls smtp -connect '$HOSTNAME:25' -servername '$HOSTNAME' -verify_return_error -brief"
check "SMTP STARTTLS on port 587" bash -c "echo | timeout 12 openssl s_client -starttls smtp -connect '$HOSTNAME:587' -servername '$HOSTNAME' -verify_return_error -brief"
check "SMTPS certificate on port 465" bash -c "echo | timeout 12 openssl s_client -connect '$HOSTNAME:465' -servername '$HOSTNAME' -verify_return_error -brief"
check "IMAPS certificate on port 993" bash -c "echo | timeout 12 openssl s_client -connect '$HOSTNAME:993' -servername '$HOSTNAME' -verify_return_error -brief"
check "HTTPS webmail endpoint" curl -fsSIL --max-time 15 "https://$WEBMAIL/"

if [[ "$fail" -ne 0 ]]; then
  echo
  echo "PROVIDER ACCEPTANCE: FAIL — do not promote IZAKHONO MAIL to production."
  exit 2
fi

echo
echo "PROVIDER ACCEPTANCE: PASS — public DNS, PTR, protocol reachability and TLS gate passed."
echo "Independent inbound/outbound delivery, mailbox login, DKIM signing/alignment, backup and restore still require separate evidence."
