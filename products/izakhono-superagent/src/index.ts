import { advance, planGoal, type AgentRun, type SuperAgentToolExecutor, type ToolRequest, type ToolResult } from '../../../src/superagent';

type Env = {
  SUPERAGENT_SECRET?: string;
  BUILDER_URL?: string;
  BUILDER_SECRET?: string;
  SEARCH_URL?: string;
  ALLOWED_FETCH_HOSTS?: string;
};

const MAX_BODY = 1_000_000;
const DEFAULT_MAX_STEPS = 40;

function json(data: unknown, status = 200): Response {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' },
  });
}

function authorized(req: Request, env: Env): boolean {
  return Boolean(env.SUPERAGENT_SECRET && req.headers.get('x-superagent-secret') === env.SUPERAGENT_SECRET);
}

async function readJson(req: Request): Promise<any> {
  const len = Number(req.headers.get('content-length') || '0');
  if (len > MAX_BODY) throw new Error('Request body too large');
  return req.json();
}

function allowedHosts(env: Env): Set<string> {
  return new Set((env.ALLOWED_FETCH_HOSTS || '').split(',').map(v => v.trim().toLowerCase()).filter(Boolean));
}

function hostAllowed(url: URL, env: Env): boolean {
  const hosts = allowedHosts(env);
  return hosts.size > 0 && hosts.has(url.hostname.toLowerCase());
}

async function builderTool(req: ToolRequest, env: Env): Promise<ToolResult> {
  if (!env.BUILDER_URL) return { ok: false, retryable: false, error: 'BUILDER_URL is not configured' };
  const base = env.BUILDER_URL.replace(/\/+$/, '');
  const target = `${base}/api/build-anything`;
  try {
    const response = await fetch(target, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        ...(env.BUILDER_SECRET ? { 'x-admin-secret': env.BUILDER_SECRET } : {}),
      },
      body: JSON.stringify({ prompt: req.input.goal, target: req.input.target || 'app', superagent_task: req.input.task }),
    });
    const text = await response.text();
    if (!response.ok) return { ok: false, retryable: response.status >= 500 || response.status === 429, error: `Builder returned ${response.status}: ${text.slice(0, 500)}` };
    return { ok: true, output: { builder: text.slice(0, 9000) }, evidence: [`Builder HTTP ${response.status}`] };
  } catch (error) {
    return { ok: false, retryable: true, error: error instanceof Error ? error.message : 'Builder request failed' };
  }
}

async function executeTool(req: ToolRequest, env: Env): Promise<ToolResult> {
  if (req.kind === 'web_research') {
    if (!env.SEARCH_URL) return { ok: false, retryable: false, error: 'SEARCH_URL is not configured' };
    try {
      const response = await fetch(env.SEARCH_URL, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ query: req.input.query || req.input.goal, task: req.input.task }),
      });
      const text = await response.text();
      if (!response.ok) return { ok: false, retryable: response.status >= 500 || response.status === 429, error: `Search provider returned ${response.status}` };
      return { ok: true, output: { results: text.slice(0, 12000) }, evidence: [`Search provider HTTP ${response.status}`] };
    } catch (error) {
      return { ok: false, retryable: true, error: error instanceof Error ? error.message : 'Research request failed' };
    }
  }

  if (req.kind === 'code' || req.kind === 'build') return builderTool(req, env);

  if (req.kind === 'artifact') {
    return {
      ok: true,
      output: {
        type: 'superagent-artifact-manifest',
        objective: req.input.goal,
        task: req.input.task,
        generated_at: new Date().toISOString(),
      },
      evidence: ['Artifact manifest generated by IZAKHONO SUPERAGENT runtime'],
    };
  }

  if (req.kind === 'file_search' || req.kind === 'file_read') {
    return { ok: false, retryable: false, error: 'File adapter requires an approved runtime connector; no implicit filesystem access is granted.' };
  }

  if (req.kind === 'repository') {
    return { ok: false, retryable: false, error: 'Repository adapter must be supplied by the approved Git/IZAKHONO repository runtime.' };
  }

  if (req.kind === 'deployment') {
    return { ok: false, retryable: false, error: 'Deployment is an authorization-gated adapter and is not executed by the base runtime.' };
  }

  if (req.kind === 'database' || req.kind === 'messaging') {
    return { ok: false, retryable: false, error: `${req.kind} requires an explicit approved adapter.` };
  }

  return { ok: false, retryable: false, error: `Unsupported tool kind: ${req.kind}` };
}

function executor(env: Env): SuperAgentToolExecutor {
  return { execute: (request) => executeTool(request, env) };
}

async function runUntilGate(run: AgentRun, env: Env): Promise<AgentRun> {
  let current = run;
  while (current.stage !== 'complete' && current.stage !== 'blocked') current = await advance(current, executor(env));
  return current;
}

export default {
  async fetch(req: Request, env: Env): Promise<Response> {
    const url = new URL(req.url);
    if (req.method === 'OPTIONS') return json({ ok: true }, 204);

    if (url.pathname === '/health' && req.method === 'GET') {
      return json({ ok: true, service: 'IZAKHONO SUPERAGENT', version: '1.0.0', runtime: 'goal-orchestrator' });
    }

    if (!authorized(req, env)) return json({ ok: false, error: 'Unauthorized' }, 401);

    if (url.pathname === '/v1/plan' && req.method === 'POST') {
      try {
        const body = await readJson(req);
        if (typeof body?.objective !== 'string' || !body.objective.trim()) return json({ ok: false, error: 'objective is required' }, 400);
        const goal = {
          id: String(body.id || `goal_${crypto.randomUUID().replaceAll('-', '')}`),
          objective: body.objective.trim().slice(0, 10000),
          context: typeof body.context === 'object' && body.context ? body.context : {},
          requestedArtifacts: Array.isArray(body.requestedArtifacts) ? body.requestedArtifacts.slice(0, 20) : [],
          maxSteps: Math.min(Number(body.maxSteps || DEFAULT_MAX_STEPS), DEFAULT_MAX_STEPS),
          autonomy: body.autonomy === 'supervised' ? 'supervised' as const : 'owner' as const,
        };
        return json({ ok: true, run: planGoal(goal) }, 201);
      } catch (error) {
        return json({ ok: false, error: error instanceof Error ? error.message : 'Invalid JSON' }, 400);
      }
    }

    if (url.pathname === '/v1/run' && req.method === 'POST') {
      try {
        const body = await readJson(req);
        if (!body?.run || !body.run.goal || !Array.isArray(body.run.tasks)) return json({ ok: false, error: 'A planned run is required' }, 400);
        const run = await runUntilGate(body.run as AgentRun, env);
        return json({ ok: run.stage === 'complete', run }, run.stage === 'complete' ? 200 : 409);
      } catch (error) {
        return json({ ok: false, error: error instanceof Error ? error.message : 'Run failed' }, 500);
      }
    }

    if (url.pathname === '/v1/fetch' && req.method === 'POST') {
      try {
        const body = await readJson(req);
        const target = new URL(String(body?.url || ''));
        if (target.protocol !== 'https:' || !hostAllowed(target, env)) return json({ ok: false, error: 'URL is not on the approved HTTPS host allowlist' }, 403);
        const response = await fetch(target, { headers: { accept: 'text/html,text/plain,application/json' } });
        const text = (await response.text()).slice(0, MAX_BODY);
        return json({ ok: response.ok, status: response.status, url: target.toString(), content: text });
      } catch (error) {
        return json({ ok: false, error: error instanceof Error ? error.message : 'Fetch failed' }, 400);
      }
    }

    return json({ ok: false, error: 'Not found' }, 404);
  },
};
