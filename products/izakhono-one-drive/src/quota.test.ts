import assert from "node:assert/strict";
import {DEFAULT_SPACE_QUOTA_BYTES,canAccessSpace,canMutateFiles,commitUpload,remainingBytes,releaseReservation,reserveUpload} from "./quota.js";
const base={quotaBytes:DEFAULT_SPACE_QUOTA_BYTES,usedBytes:0n,reservedBytes:0n};
assert.equal(DEFAULT_SPACE_QUOTA_BYTES,53687091200n);
assert.equal(remainingBytes(base),53687091200n);
assert.equal(remainingBytes({...base,usedBytes:10n,reservedBytes:5n}),53687091185n);
const reserved=reserveUpload(base,1024n);
assert.equal(reserved.reservedBytes,1024n);
assert.equal(commitUpload(reserved,1024n,1000n).usedBytes,1000n);
assert.equal(releaseReservation(reserved,1024n).reservedBytes,0n);
assert.throws(()=>reserveUpload(base,DEFAULT_SPACE_QUOTA_BYTES+1n),/quota-exceeded/);
assert.throws(()=>reserveUpload(base,0n),/upload-size-must-be-positive/);
assert.throws(()=>commitUpload(reserved,1024n,1025n),/quota-invariant-violated/);
const principal={userId:"u-1",organisationIds:new Set(["org-1"])};
assert.equal(canAccessSpace(principal,{kind:"personal",ownerUserId:"u-1"}),true);
assert.equal(canAccessSpace(principal,{kind:"personal",ownerUserId:"u-2"}),false);
assert.equal(canAccessSpace(principal,{kind:"business",organisationId:"org-1",role:"viewer"}),true);
assert.equal(canAccessSpace(principal,{kind:"business",organisationId:"org-2",role:"editor"}),false);
assert.equal(canMutateFiles("viewer"),false);
assert.equal(canMutateFiles("editor"),true);
console.log("[PASS] ONE DRIVE quota and isolation policy tests");
