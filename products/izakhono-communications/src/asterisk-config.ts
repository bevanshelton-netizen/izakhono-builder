import type { DesiredExtension, DesiredInboundRoute, DesiredOutboundRoute } from "./runtime-reconciler";

export interface ResolvedSipCredential extends DesiredExtension {
  secret: string;
}

const TOKEN = /^[A-Za-z0-9_.:+-]+$/;

function token(value: string, field: string): string {
  if (!value || !TOKEN.test(value)) throw new Error(`invalid_asterisk_${field}`);
  return value;
}

function quoteSecret(value: string): string {
  if (value.includes("\n") || value.includes("\r") || value.includes("\"")) {
    throw new Error("invalid_asterisk_secret");
  }
  return value;
}

/**
 * Renders tenant extension state as an include fragment. The caller owns the
 * final file placement and reload lifecycle. Secrets are accepted only at the
 * final rendering boundary and are never returned by diagnostic helpers.
 */
export function renderAsteriskPjsipExtensions(extensions: ResolvedSipCredential[]): string {
  return extensions.map((extension) => {
    const id = token(extension.extension, "extension");
    const username = token(extension.username, "username");
    const secret = quoteSecret(extension.secret);
    return [
      `[${id}-auth]`,
      "type=auth",
      "auth_type=userpass",
      `username=${username}`,
      `password=${secret}`,
      "",
      `[${id}-aor]`,
      "type=aor",
      "max_contacts=5",
      "remove_existing=yes",
      "",
      `[${id}](endpoint-template)`,
      `auth=${id}-auth`,
      `aors=${id}-aor`,
      `callerid=${id} <${id}>`,
      "",
    ].join("\n");
  }).join("\n");
}

export function renderAsteriskInboundRoutes(routes: DesiredInboundRoute[]): string {
  return routes.map((route) => {
    const number = token(route.number, "inbound_number");
    const destination = token(route.destination, "inbound_destination");
    return `${number} = PJSIP/${destination}`;
  }).join("\n");
}

export function renderAsteriskOutboundRoutes(routes: DesiredOutboundRoute[]): string {
  return routes.map((route) => {
    const source = token(route.source, "outbound_source");
    const destination = token(route.destination, "outbound_destination");
    return `${source} = ${destination}`;
  }).join("\n");
}

export function renderAsteriskRuntimeConfig(
  extensions: ResolvedSipCredential[],
  inboundRoutes: DesiredInboundRoute[],
  outboundRoutes: DesiredOutboundRoute[],
): { pjsipFragment: string; extensionsFragment: string } {
  const pjsipFragment = [
    "; Generated by IZAKHONO Communications OS. Do not edit manually.",
    renderAsteriskPjsipExtensions(extensions),
  ].filter(Boolean).join("\n");

  const inbound = renderAsteriskInboundRoutes(inboundRoutes);
  const outbound = renderAsteriskOutboundRoutes(outboundRoutes);
  const extensionsFragment = [
    "; Generated by IZAKHONO Communications OS. Do not edit manually.",
    "[izakhono-inbound-routes]",
    inbound || "; no inbound routes",
    "",
    "[izakhono-outbound-routes]",
    outbound || "; no outbound routes",
    "",
  ].join("\n");

  return { pjsipFragment, extensionsFragment };
}
