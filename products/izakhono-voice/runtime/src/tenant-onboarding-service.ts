import type { Pool } from "pg";

export type VoiceForwardingMode = "unconditional" | "busy" | "no_answer" | "unreachable" | "busy_no_answer_unreachable";
export interface ProvisionedVoiceNumber { phoneNumber: string; providerReference?: string; newlyProvisioned: boolean; }
export interface VoiceNumberProvisioner {
  provisionNumber(input: { tenantId: string; idempotencyKey: string }): Promise<ProvisionedVoiceNumber>;
  releaseNumber(input: { tenantId: string; phoneNumber: string; providerReference?: string }): Promise<void>;
}
export interface VoiceSubscriptionGate { assertSubscriptionActive(tenantId: string): Promise<void>; }

/** Reads entitlement written only by the trusted, verified billing-event adapter. */
export class PostgresVoiceSubscriptionGate implements VoiceSubscriptionGate {
  constructor(private readonly pool: Pool) {}
  async assertSubscriptionActive(tenantId: string): Promise<void> {
    const result = await this.pool.query(
      "SELECT 1 FROM voice_tenant_subscriptions WHERE tenant_id = $1 AND status = 'active' AND current_period_end > NOW()",
      [tenantId],
    );
    if (result.rowCount !== 1) throw new Error("An active IZAKHONO VOICE subscription is required");
  }
}
export interface VoiceTenantSetupRepository {
  createTenantVoiceSetup(input: { tenantId: string; businessName: string; customerMobileE164: string; voiceDestinationE164: string; forwardingMode: VoiceForwardingMode; systemInstructions: string }): Promise<void>;
}
export interface VoiceOnboardingRequest {
  /** Derived by the authenticated application server, never from a browser-supplied tenant ID. */
  authenticatedTenantId: string;
  /** Stable request key supplied/generated by the trusted application server. */
  idempotencyKey: string;
  businessName: string;
  customerMobileE164: string;
  forwardingMode: VoiceForwardingMode;
  systemInstructions: string;
}
export interface VoiceOnboardingResult {
  tenantId: string; businessName: string; customerMobileE164: string; voiceDestinationE164: string;
  forwardingMode: VoiceForwardingMode; forwardingStatus: "pending";
}

/** Trusted orchestration boundary: subscription -> number -> durable tenant setup. */
export class VoiceTenantOnboardingService {
  constructor(
    private readonly subscriptions: VoiceSubscriptionGate,
    private readonly numbers: VoiceNumberProvisioner,
    private readonly repository: VoiceTenantSetupRepository,
  ) {}

  async onboard(request: VoiceOnboardingRequest): Promise<VoiceOnboardingResult> {
    const tenantId = request.authenticatedTenantId.trim();
    const businessName = request.businessName.trim();
    const customerMobileE164 = request.customerMobileE164.trim();
    const systemInstructions = request.systemInstructions.trim();
    const idempotencyKey = request.idempotencyKey.trim();
    if (!tenantId) throw new Error("Authenticated tenant context is required");
    if (!idempotencyKey) throw new Error("Idempotency key is required");
    if (businessName.length < 2 || businessName.length > 120) throw new Error("Business name must be 2 to 120 characters");
    if (!/^[+][1-9][0-9]{7,14}$/.test(customerMobileE164)) throw new Error("Customer mobile number must be valid E.164");
    if (!systemInstructions || systemInstructions.length > 12000) throw new Error("Business instructions are required and must not exceed 12000 characters");
    if (!["unconditional", "busy", "no_answer", "unreachable", "busy_no_answer_unreachable"].includes(request.forwardingMode)) {
      throw new Error("Unsupported call-forwarding mode");
    }

    await this.subscriptions.assertSubscriptionActive(tenantId);
    const assigned = await this.numbers.provisionNumber({ tenantId, idempotencyKey });
    if (!/^[+][1-9][0-9]{7,14}$/.test(assigned.phoneNumber)) {
      if (assigned.newlyProvisioned) { try { await this.numbers.releaseNumber({ tenantId, phoneNumber: assigned.phoneNumber, providerReference: assigned.providerReference }); } catch { /* provider reconciliation */ } }
      throw new Error("Telephony provider returned an invalid E.164 destination number");
    }

    try {
      await this.repository.createTenantVoiceSetup({
        tenantId, businessName, customerMobileE164, voiceDestinationE164: assigned.phoneNumber,
        forwardingMode: request.forwardingMode, systemInstructions,
      });
    } catch (error) {
      if (assigned.newlyProvisioned) { try { await this.numbers.releaseNumber({ tenantId, phoneNumber: assigned.phoneNumber, providerReference: assigned.providerReference }); } catch { /* provider reconciliation */ } }
      throw error;
    }
    return { tenantId, businessName, customerMobileE164, voiceDestinationE164: assigned.phoneNumber,
      forwardingMode: request.forwardingMode, forwardingStatus: "pending" };
  }
}

/** PostgreSQL implementation; tenant setup is committed atomically. */
export class PostgresVoiceTenantSetupRepository implements VoiceTenantSetupRepository {
  constructor(private readonly pool: Pool) {}
  async createTenantVoiceSetup(input: Parameters<VoiceTenantSetupRepository["createTenantVoiceSetup"]>[0]): Promise<void> {
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      await client.query(
        "INSERT INTO voice_tenant_policies (tenant_id, system_instructions, enabled) VALUES ($1, $2, TRUE) ON CONFLICT (tenant_id) DO UPDATE SET system_instructions = EXCLUDED.system_instructions, enabled = TRUE, updated_at = NOW()",
        [input.tenantId, "Business name: " + input.businessName + "\n\n" + input.systemInstructions],
      );
      const numberMapping = await client.query(
        "INSERT INTO voice_tenant_numbers (phone_number, tenant_id, enabled) VALUES ($1, $2, TRUE) ON CONFLICT (phone_number) DO UPDATE SET enabled = TRUE, updated_at = NOW() WHERE voice_tenant_numbers.tenant_id = EXCLUDED.tenant_id RETURNING phone_number",
        [input.voiceDestinationE164, input.tenantId],
      );
      if (numberMapping.rowCount !== 1) throw new Error("AI destination number is already assigned to another tenant");
      await client.query(
        "INSERT INTO voice_customer_endpoints (tenant_id, business_name, customer_mobile_e164, voice_destination_e164, forwarding_mode, forwarding_status) VALUES ($1, $2, $3, $4, $5, 'pending') ON CONFLICT (tenant_id, customer_mobile_e164) DO UPDATE SET business_name = EXCLUDED.business_name, voice_destination_e164 = EXCLUDED.voice_destination_e164, forwarding_mode = EXCLUDED.forwarding_mode, forwarding_status = 'pending', verified_at = NULL, updated_at = NOW()",
        [input.tenantId, input.businessName, input.customerMobileE164, input.voiceDestinationE164, input.forwardingMode],
      );
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK").catch(() => undefined);
      throw error;
    } finally { client.release(); }
  }
}
